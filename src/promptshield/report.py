"""Render scan results as text, JSON or a standalone HTML report."""

from __future__ import annotations

import html
import json
from collections.abc import Sequence
from datetime import UTC, datetime

from . import __version__
from .scanner import ScanResult

_COLORS = {"critical": "#b42318", "high": "#c4320a", "medium": "#b54708", "low": "#175cd3", "info": "#475467"}
_VERDICT_COLORS = {"allow": "#067647", "review": "#b54708", "block": "#b42318"}


def to_text(result: ScanResult) -> str:
    lines = [f"verdict: {result.verdict.upper()}  score: {result.score}/100  mode: {result.mode}"]
    if not result.findings:
        lines.append("no findings")
    for f in result.findings:
        lines.append(f"  [{f.severity.name:<8}] {f.detector}: {f.message}")
        if f.evidence:
            lines.append(f"             evidence: {f.evidence}")
    return "\n".join(lines)


def to_json(results: Sequence[ScanResult], label: str | None = None) -> str:
    payload = {
        "tool": "promptshield",
        "version": __version__,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "results": [dict(r.to_dict(), label=label) if label else r.to_dict() for r in results],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


def to_html(results: Sequence[ScanResult], title: str = "promptshield report") -> str:
    esc = html.escape
    sections = []
    for i, r in enumerate(results, 1):
        rows = (
            "".join(
                f"<tr><td><span class='sev' style='background:{_COLORS[f.severity.name.lower()]}'>{f.severity.name}</span></td>"
                f"<td>{esc(f.detector)}</td><td>{esc(f.message)}</td><td><code>{esc(f.evidence)}</code></td></tr>"
                for f in r.findings
            )
            or "<tr><td colspan='4'>No findings</td></tr>"
        )
        sections.append(
            f"<section><h2>Scan {i} &middot; {esc(r.mode)}</h2>"
            f"<p><span class='verdict' style='background:{_VERDICT_COLORS[r.verdict]}'>{r.verdict.upper()}</span> "
            f"risk score <strong>{r.score}</strong>/100</p>"
            f"<table><thead><tr><th>Severity</th><th>Detector</th><th>Finding</th><th>Evidence</th></tr></thead>"
            f"<tbody>{rows}</tbody></table></section>"
        )
    return (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        f"<meta name='viewport' content='width=device-width,initial-scale=1'><title>{esc(title)}</title><style>"
        "body{font:15px/1.5 system-ui,sans-serif;margin:2rem auto;max-width:960px;padding:0 1rem;color:#101828}"
        "table{border-collapse:collapse;width:100%}th,td{text-align:left;padding:.5rem;border-bottom:1px solid #eaecf0;vertical-align:top}"
        ".sev,.verdict{color:#fff;border-radius:4px;padding:.1rem .45rem;font-size:12px;font-weight:600}"
        "code{word-break:break-all}section{margin-bottom:2rem}"
        f"</style></head><body><h1>{esc(title)}</h1><p>Generated by promptshield {__version__}</p>"
        + "".join(sections)
        + "</body></html>"
    )


_SARIF_LEVEL = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}


def to_sarif(results: Sequence[ScanResult], uri: str = "stdin", source: str = "") -> str:
    """Render results as SARIF 2.1.0 so GitHub code scanning shows them as alerts.

    When ``source`` is given, each finding is pinned to the first line where its
    evidence appears verbatim; otherwise it points at line 1.
    """
    lines = source.splitlines()

    def line_of(evidence: str) -> int:
        if evidence:
            for number, line in enumerate(lines, 1):
                if evidence in line:
                    return number
        return 1

    rules: dict[str, dict] = {}
    sarif_results = []
    for result in results:
        for f in result.findings:
            rules.setdefault(
                f.detector,
                {"id": f.detector, "name": f.detector, "shortDescription": {"text": f.detector.replace("_", " ")}},
            )
            sarif_results.append(
                {
                    "ruleId": f.detector,
                    "level": _SARIF_LEVEL[f.severity.name.lower()],
                    "message": {"text": f"{f.message} (verdict {result.verdict}, score {result.score})"},
                    "locations": [
                        {
                            "physicalLocation": {
                                "artifactLocation": {"uri": uri},
                                "region": {"startLine": line_of(f.evidence)},
                            }
                        }
                    ],
                    "properties": {"severity": f.severity.name.lower(), "mode": result.mode},
                }
            )
    payload = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "promptshield",
                        "version": __version__,
                        "informationUri": "https://github.com/kirtanbhatt10/promptshield",
                        "rules": list(rules.values()),
                    }
                },
                "results": sarif_results,
            }
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)
